def font(sz, bold=False):
    p = r"C:\Windows\Fonts\msyhbd.ttc" if bold else r"C:\Windows\Fonts\msyh.ttc"
    return ImageFont.truetype(p, sz) if os.path.exists(p) else ImageFont.load_default()


F_T, F_M, F_S = font(21, True), font(15, True), font(13)


def draw_bands(im, bands, sc, dy):
    """只画彩色框线，一个字都不写（文字全部去右侧图例）。"""
    d = ImageDraw.Draw(im)
    for name, y0, y1, col, _ in bands:
        Y0 = int((y0 - dy) * sc)
        Y1 = int((y1 - dy) * sc)
        d.rectangle([0, Y0, im.size[0] - 1, max(Y1, Y0 + 1)], outline=col, width=2)
    return im


def brace(im, x, y0, y1, col, sc):
    d = ImageDraw.Draw(im)
    a, b = int(y0 * sc), int(y1 * sc)
    d.line([x, a, x, b], fill=col, width=3)
    d.line([x - 12, a, x, a], fill=col, width=3)
    d.line([x - 12, b, x, b], fill=col, width=3)
    return im


def legend(d, x, y, bands, extra=()):
    for name, y0, y1, col, txt in bands:
        d.rectangle([x, y + 3, x + 12, y + 15], fill=col)
        d.text((x + 20, y), "y%-4d" % y0, font=F_S, fill=col)
        d.text((x + 66, y), txt, font=F_S, fill=(214, 206, 190))
        y += 22
    y += 6
    for txt, col in extra:
        d.text((x, y), txt, font=F_S, fill=col)
        y += 22
    return y


